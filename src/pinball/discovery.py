"""Build the model pool from the upstream's /models list plus the shipped catalogue.

Live fields win over the catalogue (src/pinball/catalog.json, regenerated by
scripts/build_catalog.py); unknown models get conservative defaults. Tiers are
inferred: vendor category, then Terminal-Bench accuracy, then output price,
else standard. See docs/self-discovery.md.
"""

from __future__ import annotations

import json
import logging
import re
import urllib.error
import urllib.request
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Final

from pinball.config import TIER_ORDER, Config, ModelSpec, Tier

log = logging.getLogger("pinball")

CATALOG_PATH: Final = Path(__file__).with_name("catalog.json")
# Embeddings, dated snapshots (aliases of a newer id) and legacy GPT-3.5/4/4o.
IGNORE: Final = re.compile(r"(embed|-\d{4}-\d{2}-\d{2}$|-\d{4}$|^gpt-3\.5|^gpt-4(o)?(-|$))")
DEFAULT_PROMPT_TOKENS: Final = 100_000
PROMPT_TOKENS_CAP: Final = 250_000  # beyond this a window is a cost risk, not a help
HEAVY_TBENCH: Final = 55.0
STANDARD_TBENCH: Final = 35.0
LIGHT_MAX_COST_OUT: Final = 2.0
HEAVY_MIN_COST_OUT: Final = 20.0
_CATEGORY: Final = {"lightweight": Tier.LIGHT, "versatile": Tier.STANDARD, "powerful": Tier.HEAVY}
_ENDPOINT_API: Final = {
    "/chat/completions": "chat",
    "/responses": "responses",
    "/v1/messages": "messages",
    "/messages": "messages",
}


class DiscoveryError(RuntimeError):
    pass


@dataclass(frozen=True, slots=True)
class Found:
    id: str
    spec: ModelSpec
    tier: Tier
    rank: tuple[float, float, str]  # sort key inside a tier
    why: str  # which rule set the tier


def load_catalog(path: Path = CATALOG_PATH) -> dict[str, dict[str, Any]]:
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)["models"]


def _map(v: Any) -> dict[str, Any]:
    return v if isinstance(v, dict) else {}


def _int(v: Any) -> int | None:
    return v if isinstance(v, int) and not isinstance(v, bool) and v > 0 else None


def _tier(category: Any, cat: dict[str, Any]) -> tuple[Tier, str]:
    if isinstance(category, str) and category in _CATEGORY:
        return _CATEGORY[category], f"category:{category}"
    tb = cat.get("tbench")
    if isinstance(tb, int | float):
        if tb >= HEAVY_TBENCH:
            return Tier.HEAVY, f"tbench:{tb}"
        if tb >= STANDARD_TBENCH:
            return Tier.STANDARD, f"tbench:{tb}"
        return Tier.LIGHT, f"tbench:{tb}"
    cost = cat.get("cost_out")
    if isinstance(cost, int | float):
        if cost <= LIGHT_MAX_COST_OUT:
            return Tier.LIGHT, f"cost:{cost}"
        if cost >= HEAVY_MIN_COST_OUT:
            return Tier.HEAVY, f"cost:{cost}"
        return Tier.STANDARD, f"cost:{cost}"
    return Tier.STANDARD, "default"


def classify(raw: dict[str, Any], catalog: dict[str, dict[str, Any]]) -> Found | None:
    """One /models entry -> Found, or None for non-chat, ignored or hidden ids."""
    mid = raw.get("id")
    if not isinstance(mid, str) or not mid or IGNORE.search(mid):
        return None
    caps = _map(raw.get("capabilities"))
    if caps.get("type") not in (None, "chat") or raw.get("model_picker_enabled") is False:
        return None
    if raw.get("type") == "embedding":
        return None
    cat = catalog.get(mid, {})
    limits = _map(caps.get("limits"))
    supports = _map(caps.get("supports"))

    window = (
        _int(limits.get("max_prompt_tokens"))
        or _int(raw.get("max_input_tokens"))  # Anthropic
        or _int(raw.get("inputTokenLimit"))  # Gemini
        or _int(cat.get("input"))
        or _int(cat.get("context"))
        or DEFAULT_PROMPT_TOKENS
    )
    vision = supports.get("vision")
    if not isinstance(vision, bool):
        vision = bool(cat.get("vision", False))

    endpoints = raw.get("supported_endpoints")
    api: tuple[str, ...] = ()
    if isinstance(endpoints, list):
        api = tuple(sorted({_ENDPOINT_API[e] for e in endpoints if e in _ENDPOINT_API}))
        if not api:
            return None  # nothing pinball's clients can call

    efforts: tuple[str, ...] | None = None
    if "reasoning_effort" in supports:
        live = supports["reasoning_effort"]
        efforts = tuple(str(x) for x in live) if isinstance(live, list) else ()
    elif supports:  # a live capabilities block that omits it: the model rejects the parameter
        efforts = ()
    elif cat.get("efforts"):
        efforts = tuple(cat["efforts"])

    spec = ModelSpec(
        prompt_tokens=min(window, PROMPT_TOKENS_CAP), vision=vision, api=api, efforts=efforts
    )
    tier, why = _tier(raw.get("model_picker_category"), cat)
    tb = cat.get("tbench")
    cost = cat.get("cost_out")
    rank = (
        -float(tb) if isinstance(tb, int | float) else 0.0,
        float(cost) if isinstance(cost, int | float) else 1e9,
        mid,
    )
    return Found(mid, spec, tier, rank, why)


def build_pool(
    payload: Any, catalog: dict[str, dict[str, Any]]
) -> tuple[dict[str, ModelSpec], dict[Tier, tuple[str, ...]], list[Found]]:
    data = payload.get("data") if isinstance(payload, dict) else None
    if not isinstance(data, list):
        raise DiscoveryError("models answer has no data list")
    found: dict[str, Found] = {}
    for raw in data:
        if isinstance(raw, dict) and (f := classify(raw, catalog)) is not None:
            found.setdefault(f.id, f)
    if not found:
        raise DiscoveryError("no chat models listed")
    tiers: dict[Tier, list[Found]] = {t: [] for t in TIER_ORDER}
    for f in found.values():
        tiers[f.tier].append(f)
    ordered = {t: [f.id for f in sorted(fs, key=lambda f: f.rank)] for t, fs in tiers.items()}
    # An empty tier borrows the best model of the nearest non-empty tier (upward first).
    for i, t in enumerate(TIER_ORDER):
        if not ordered[t]:
            near = sorted(
                (o for o in TIER_ORDER if ordered[o] and o != t),
                key=lambda o: (abs(TIER_ORDER.index(o) - i), -TIER_ORDER.index(o)),
            )
            ordered[t] = [ordered[near[0]][0]]
    models = {f.id: f.spec for f in found.values()}
    return models, {t: tuple(v) for t, v in ordered.items()}, list(found.values())


def apply_pool(
    base: Config, models: dict[str, ModelSpec], tiers: dict[Tier, tuple[str, ...]]
) -> Config:
    """base with the discovered pool; `pin`ned models move to the front of their tier."""
    pinned = {t: tuple(n for n in base.pin.get(t, ()) if n in models) for t in TIER_ORDER}
    out = {t: (*pinned[t], *(n for n in tiers[t] if n not in pinned[t])) for t in TIER_ORDER}
    return Config.model_validate({**base.model_dump(), "models": models, "tiers": out})


def fetch(
    url: str, token: str = "", opener: Callable[..., Any] | None = None, timeout: float = 30.0
) -> Any:
    headers = {"accept": "application/json"}
    if token:
        headers["authorization"] = f"Bearer {token}"
    req = urllib.request.Request(url, headers=headers)
    try:
        with (opener or urllib.request.urlopen)(req, timeout=timeout) as r:
            return json.loads(r.read())
    except urllib.error.HTTPError as e:
        raise DiscoveryError(f"models HTTP {e.code}") from None
    except (urllib.error.URLError, OSError, ValueError) as e:
        raise DiscoveryError(f"models transport {type(e).__name__}") from None


def discover(
    base: Config,
    url: str,
    token: str = "",
    catalog: dict[str, dict[str, Any]] | None = None,
    opener: Callable[..., Any] | None = None,
) -> tuple[Config, Any]:
    """(config with the live pool, raw payload to cache)."""
    payload = fetch(url, token, opener)
    models, tiers, found = build_pool(payload, load_catalog() if catalog is None else catalog)
    for f in sorted(found, key=lambda f: (TIER_ORDER.index(f.tier), f.rank)):
        log.debug("discovered model=%s tier=%s why=%s", f.id, f.tier, f.why)
    return apply_pool(base, models, tiers), payload


def from_cache(
    base: Config, path: Path, catalog: dict[str, dict[str, Any]] | None = None
) -> Config:
    with path.open(encoding="utf-8") as fh:
        payload = json.load(fh)
    models, tiers, _ = build_pool(payload, load_catalog() if catalog is None else catalog)
    return apply_pool(base, models, tiers)


def save_cache(path: Path, payload: Any) -> None:
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(payload), encoding="utf-8")
    tmp.replace(path)
